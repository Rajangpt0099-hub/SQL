-- List every booking along with the passenger's name and the train name used.
select tb.booking_id, p.passenger_name, t.train_name,tb.*
from Passengers p
inner join TicketBookings tb
on tb.passenger_id = p.passenger_id
inner join Trains t 
on tb.train_id = t.train_id;

-- Find the total number of bookings made for each train.
select t.train_name, count(tb.booking_id) as Total_Bookings
from Trains t
inner join TicketBookings tb
on t.train_id = tb.train_id
group by t.train_id, t.train_name;

-- Find trains that have been booked more than 60 times.
select t.train_name, count(tb.booking_id) as Total_Bookings
from Trains t
inner join TicketBookings tb
on t.train_id = tb.train_id
group by  t.train_id, t.train_name
having count(tb.booking_id) > 60;

--  Find the total fare collected at each boarding station
select s.station_name, sum(tb.fare) as Total_Fare_Collected
from Stations s
inner join TicketBookings tb
on s.station_id = tb.boarding_station_id
group by s.station_id, s.station_name;

--  Find stations that have never been used as a boarding station.
select s.station_id, s.station_name
from Stations s
left join TicketBookings tb
on s.station_id = tb.boarding_station_id
where tb.booking_id is null;

